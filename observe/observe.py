"""observe — render a web page and record what it shows.

    observe URL [URL ...] --contact URL [--shots DIR] [--mandate REF]  >  observations.jsonl

One JSON line per page. No judgement happens here: this program only
records the rendered surface. Judgement belongs to `releve`.

Conduct, enforced here and nowhere else:
  - robots.txt is read before the first request to a site and obeyed (RFC 9309);
    a site that does not answer for it is left alone. Only the site owner's
    written leave (--mandate) overrides it, and the leave is recorded.
  - Pages are fetched one at a time, at least PAUSE seconds apart per site,
    longer if robots.txt asks.
  - Only web addresses (http, https) are observed.
  - A page that answers with an error, or puts a CAPTCHA or challenge before its
    content, is left alone at once: no retry, no workaround. When the answer is
    the site pushing back (429, 503, a challenge), the whole site is left alone
    for the rest of the run.
  - Wherever a page leads the browser, by redirect, refresh or script, the
    address is requested only if robots.txt admits it. The leave of one site's
    owner never extends to another site.
  - What a page loads into itself (images, scripts, frames) is fetched as any
    browser would fetch it.
  - Nothing is submitted, by the robot or by a page's own script; no window is
    opened, no dialog is dismissed, no session is kept.
  - What a page asks of the device on arrival is noted and not granted. What an
    image file says of its own making is read from the bytes already fetched.
  - Of what a page says, extracts of 80 characters at most are kept. What each
    block says is weighed, in words and in bits, and not kept.
  - The page is taken by keyboard once, after it has been recorded: Tab and,
    where Tab holds, Shift+Tab and Escape. No other key is pressed: nothing is
    typed, chosen or activated.
  - The robot names itself and says where its operator can be reached.
"""
import argparse, base64, hashlib, json, socket, sys, time, urllib.error, urllib.parse, urllib.request, urllib.robotparser
from datetime import datetime, timezone
from pathlib import Path
from playwright.sync_api import Error as BrowserError, sync_playwright

AGENT = "releve-observe/0.5"
PAUSE = 1.0   # seconds between two pages of one site, at least
DESKTOP = {"width": 1280, "height": 800}
NARROW = {"width": 320, "height": 800}
LIMIT = 2500  # surfaces per page
TABS = 120    # Tab presses at most, in the keyboard walk
LOOKS = 30    # stops whose focus is looked at, at most

# Interstitials that stand between a robot and the content. A CAPTCHA inside a
# form is not one: forms are never submitted.
GATE_TITLES = ("just a moment", "attention required", "checking your browser", "un instant…", "un instant...",
               "access to this page has been denied")
GATE_ADDRESSES = ("/cdn-cgi/challenge-platform", "captcha-delivery.com", "perimeterx", "px-captcha")
GATE_FRAMES = GATE_ADDRESSES[1:]  # a wall's frame; the first is also the address of a widget inside a form
PUSHBACK = (429, 503)  # the site, not the page, is saying no

# Hosts of conversational widgets. A match means "look here", not a verdict.
WIDGETS = {
    "intercom": "intercom", "drift.com": "drift", "crisp.chat": "crisp",
    "tidio": "tidio", "zdassets.com": "zendesk", "usemessages.com": "hubspot",
    "livechatinc.com": "livechat", "tawk.to": "tawk", "botpress": "botpress",
    "voiceflow": "voiceflow", "chatbase": "chatbase", "landbot": "landbot",
    "ada.support": "ada", "freshchat": "freshchat", "olark": "olark",
    "userlike": "userlike", "iadvize": "iadvize", "df-messenger": "dialogflow",
}
DISCLOSURE = [
    "intelligence artificielle", "assistant virtuel", "agent conversationnel",
    "chatbot", "robot conversationnel", "généré par", "artificial intelligence",
    "virtual assistant", "ai assistant", "ai-generated", "generated by ai",
]

# What an image file may say of its own making: the IPTC digital source types that name a
# synthetic origin, and the signatures some generators leave. A match is the file's own
# statement, read; it is not a finding about the picture.
ORIGINS = ["compositeWithTrainedAlgorithmicMedia", "trainedAlgorithmicMedia", "compositeSynthetic", "algorithmicMedia",
           "Midjourney", "DALL-E", "DALL·E", "Stable Diffusion", "Adobe Firefly", "ComfyUI", "NovelAI", "Made with Google AI"]
HEAVIEST = 8_000_000  # bytes of an image whose file is read for such a statement
# What a page may ask of the device. Asked on arrival, it is noted and not granted.
ASKING = """window.__opened = 0; window.open = () => { window.__opened++; return null; };
window.__asked = []; { const note = n => { if (!window.__asked.includes(n)) window.__asked.push(n); };
  if (window.Notification) Notification.requestPermission = () => (note("notifications"), Promise.resolve("default"));
  if (navigator.geolocation) { navigator.geolocation.getCurrentPosition = () => note("location"); navigator.geolocation.watchPosition = () => (note("location"), 0); }
  if (navigator.mediaDevices) navigator.mediaDevices.getUserMedia = () => (note("camera or microphone"), Promise.reject(new DOMException("denied", "NotAllowedError"))); }"""

EXTRACT = Path(__file__).with_name("extract.js").read_text(encoding="utf-8")
KEYS = Path(__file__).with_name("keys.js").read_text(encoding="utf-8")
SPACED = Path(__file__).with_name("spacing.js").read_text(encoding="utf-8")
DEEPEST = "() => { let e = document.activeElement; while (e && e.shadowRoot && e.shadowRoot.activeElement) e = e.shadowRoot.activeElement; return e; }"


class Refused(Exception):
    """The site said no, in one of the ways a robot must hear. `whole`: no to the robot, not to one page."""
    def __init__(self, why, whole=False):
        super().__init__(why)
        self.whole = whole


def place(url):
    """The origin and the site of a web address, or None. A site is a host, whatever the scheme, port or www."""
    try:
        p = urllib.parse.urlsplit(url)
        p.port
    except ValueError:
        return None
    if p.scheme not in ("http", "https") or not p.hostname:
        return None
    return f"{p.scheme}://{p.netloc}", p.hostname.removeprefix("www.")


def robots(origin, agent, shut=None):
    """The site's rules, or None when it must be left alone. RFC 9309: a 4xx
    means no rules; an unreachable or failing server means stay out. `shut`
    says why an address may not be requested at all, wherever a redirect leads."""
    class Guarded(urllib.request.HTTPRedirectHandler):
        def redirect_request(self, req, fp, code, msg, headers, to):
            if shut and shut(to):
                raise urllib.error.URLError(shut(to))
            return super().redirect_request(req, fp, code, msg, headers, to)
    rp = urllib.robotparser.RobotFileParser()
    try:
        req = urllib.request.Request(origin + "/robots.txt", headers={"User-Agent": agent})
        with urllib.request.build_opener(Guarded).open(req, timeout=10) as r:
            rp.parse(r.read(500_000).decode("utf-8", "replace").splitlines())
    except urllib.error.HTTPError as e:
        if not 400 <= e.code < 500:
            return None
        rp.allow_all = True
    except OSError:
        return None
    return rp


def started(i):
    """The address whose loading asked for a request: the document that names it, or the script that fetched it."""
    if i.get("url"):
        return i["url"]
    stack = i.get("stack")
    while stack:
        for frame in stack.get("callFrames", []):
            if frame.get("url", "").startswith(("http://", "https://")):
                return frame["url"]
        stack = stack.get("parent")
    return None


def resource(r, kind, size):
    """One response as the record keeps it: what it is, what it weighs, how it travelled, whether it may be kept."""
    h = {k.lower(): v for k, v in r.get("headers", {}).items()}
    control = h.get("cache-control", "").lower()
    return {"url": r["url"], "kind": kind, "mime": r.get("mimeType", ""), "bytes": size, "proto": r.get("protocol", ""),
            "encoded": h.get("content-encoding", ""),
            "cached": "no-store" not in control and ("max-age" in control or any(k in h for k in ("etag", "last-modified", "expires")))}


def key(s):
    ident = "|".join(str(s.get(k) or "") for k in ("kind", "sel", "name", "text", "src"))
    return hashlib.sha1(ident.encode()).hexdigest()[:10]


SPACING = ("*{line-height:1.5!important;letter-spacing:.12em!important;word-spacing:.16em!important}"
           "p{margin-bottom:2em!important}")


def walk(page):
    """The page by keyboard alone, from the top: Tab after Tab, until the focus leaves the page, goes
    round without reaching the rest, holds still, or TABS presses have been made. At each of the first
    LOOKS stops, the screen with the element focused is compared with the screen with it left: where
    not one pixel differs, the focus shows nothing. Facts only: which stops, how it ended."""
    def shot(clip=None):
        return page.screenshot(clip=clip, animations="disabled", caret="hide")

    def seen(here):
        x, y, w, h = here["box"]
        view = page.viewport_size
        if w <= 0 or h <= 0 or x + w <= 0 or y + h <= 0 or x >= view["width"] or y >= view["height"]:
            return None  # not on the screen: nothing to look at
        el = page.evaluate_handle(DEEPEST)
        near = {"x": max(0, x - 12), "y": max(0, y - 12)}
        near.update(width=min(view["width"], x + w + 12) - near["x"], height=min(view["height"], y + h + 12) - near["y"])
        for clip in (near, None):  # close by first; then the whole screen, where close by nothing changed
            focused = shot(clip)
            el.evaluate("e => e.blur()")
            left = shot(clip)
            el.evaluate("e => e.focus({ preventScroll: true })")
            if focused != left:
                return True
        return False

    page.evaluate("window.scrollTo(0, 0)")
    page.evaluate_handle(DEEPEST).evaluate("e => e && e.blur && e.blur()")
    order, unseen, looked, ended, trap, held = [], [], 0, "cap", None, 0
    for _ in range(TABS):
        page.keyboard.press("Tab")
        here = page.evaluate(KEYS)
        at = here["at"]
        if at is None:
            ended = "left"
            break
        if order and at == order[-1]:
            if here["frame"]:  # within a frame of its own: the focus moves where the robot does not follow
                held += 1
                if held >= 40:
                    ended = "frame"
                    break
                continue
            page.keyboard.press("Shift+Tab")  # Tab held still: does anything else lead out?
            page.keyboard.press("Escape")
            page.keyboard.press("Tab")
            if page.evaluate(KEYS)["at"] == at:
                ended, trap = "stuck", at
                break
            continue
        held = 0
        if at in order:  # round again, short of the page's end
            ended, trap = ("cycled", None) if at == order[0] else ("loop", at)
            break
        order.append(at)
        if looked < LOOKS and not here["frame"]:
            visible = seen(here)
            if visible is not None:
                looked += 1
                if not visible:
                    unseen.append(at)
    return {"stops": len(order), "ended": ended, "trap": trap, "checked": looked, "unseen": unseen[:20]}


def observe(browser, url, agent, shots, closed, shut=None):
    """One page, rendered and recorded. `closed` says why the page may not go to an address;
    `shut`, when given, says why nothing at all may be requested from one, and every request
    the page makes is put to it."""
    ctx = browser.new_context(viewport=DESKTOP, user_agent=f"Mozilla/5.0 (compatible; {agent})",
                              accept_downloads=False, service_workers="block")
    try:
        # One page is observed; it opens no other. What it tried to open by itself is counted.
        ctx.add_init_script(ASKING)
        page = ctx.new_page()
        cdp = ctx.new_cdp_session(page)
        cdp.send("Network.enable")
        responses, weights, hops, asked = {}, {}, [], {}

        def sent(e):
            if "redirectResponse" in e:
                hops.append(e["redirectResponse"])
            asked.setdefault(e["requestId"], started(e.get("initiator", {})))
        cdp.on("Network.requestWillBeSent", sent)
        cdp.on("Network.responseReceived", lambda e: responses.__setitem__(e["requestId"], (e["response"], e.get("type", "Other"))))
        cdp.on("Network.loadingFinished", lambda e: weights.__setitem__(
            e["requestId"], int(e.get("encodedDataLength", 0))))

        # Every document asked for waits here. The page's own, by redirect, refresh or script, is
        # requested only where the rules admit its address; a form sent by a script is never sent.
        frame = cdp.send("Page.getFrameTree")["frameTree"]["frame"]["id"]
        barred = []

        def gate(e):
            to, document = e["request"]["url"], e.get("resourceType") == "Document"
            away = document and ("a script submits a form" if e["request"]["method"] != "GET"
                                 else closed(to) if e["frameId"] == frame else None)
            if away:
                barred.append(f"leads to {to}, where {away}")
            if away or (shut and shut(to)):
                cdp.send("Fetch.failRequest", {"requestId": e["requestId"], "errorReason": "BlockedByClient"})
            else:
                cdp.send("Fetch.continueRequest", {"requestId": e["requestId"]})

        cdp.on("Fetch.requestPaused", gate)
        cdp.send("Fetch.enable", {"patterns": [{} if shut else {"resourceType": "Document"}]})

        try:
            answer = page.goto(url, wait_until="load", timeout=45000)
        except BrowserError:
            if barred:
                raise Refused(barred[0]) from None
            raise
        if answer and answer.status >= 400:
            raise Refused(f"answered {answer.status}", whole=answer.status in PUSHBACK)
        try:
            page.wait_for_load_state("networkidle", timeout=15000)
        except BrowserError:
            pass
        frames = " ".join(f.url for f in page.frames[1:]).lower()
        if (page.title().strip().lower().startswith(GATE_TITLES) or any(g in page.url.lower() for g in GATE_ADDRESSES)
                or any(g in frames for g in GATE_FRAMES)):
            raise Refused("a challenge stands before the content", whole=True)

        # To its end, and once more if reaching the end made the page a screen longer.
        grows = [page.evaluate("document.documentElement.scrollHeight")]
        while len(grows) < 3 and (len(grows) < 2 or grows[-1] - grows[-2] >= DESKTOP["height"]):
            page.evaluate("window.scrollTo(0, document.documentElement.scrollHeight)")
            page.wait_for_timeout(800)
            grows.append(page.evaluate("document.documentElement.scrollHeight"))
        page.evaluate("window.scrollTo(0, 0)")
        page.wait_for_timeout(300)
        try:
            page.wait_for_load_state("networkidle", timeout=5000)
        except BrowserError:
            pass
        # The footprint is the page as a reader's browser loads it at this width, scrolled once to
        # its end, every redirect hop counted. It closes here: what the measuring itself fetches
        # (the screenshot, the narrow pass) is not the page's, and a data: address is not a request.
        # Each response says which address asked for it: the chain of requests is read from these links.
        fetched = [dict(resource(r, kind, weights.get(rid, 0)), **({"from": asked[rid]} if asked.get(rid) else {}))
                   for rid, (r, kind) in responses.items()] \
            + [resource(h, "Redirect", int(h.get("encodedDataLength", 0))) for h in hops]
        fetched = [f for f in fetched if f["url"].startswith(("http://", "https://"))]
        secured = next((r.get("securityDetails", {}).get("protocol") for r, kind in responses.values() if kind == "Document"), None)
        # What each image file says of its own making, read from the bytes already fetched.
        origins = {}
        for rid, (r, _) in list(responses.items())[:400]:
            if r.get("mimeType", "").startswith("image/") and 0 < weights.get(rid, 0) <= HEAVIEST:
                try:
                    body = cdp.send("Network.getResponseBody", {"requestId": rid})
                except BrowserError:
                    continue
                raw = base64.b64decode(body["body"]) if body.get("base64Encoded") else body["body"].encode("utf-8", "replace")
                said = next((o for o in ORIGINS if o.encode("utf-8") in raw), None) or (b"tEXtparameters\x00" in raw and "Stable Diffusion") or None
                origins[r["url"]] = (said, b"c2pa" in raw and (b"jumb" in raw or b"jumd" in raw))

        data = page.evaluate(EXTRACT, {"limit": LIMIT, "phrases": DISCLOSURE})
        shot = page.screenshot(full_page=True)
        page.set_viewport_size(NARROW)
        page.wait_for_timeout(400)
        data["page"]["reflow"] = page.evaluate("document.documentElement.scrollWidth")
        page.set_viewport_size(DESKTOP)
        page.wait_for_timeout(300)
        data["page"]["spaced"] = page.evaluate(SPACED, SPACING)
        final = page.url
        # The keyboard walk comes last: what a key may open or move is not part of what was recorded.
        page.set_viewport_size(DESKTOP)
        page.wait_for_timeout(300)
        try:
            data["page"]["keys"] = walk(page)
        except BrowserError:
            data["page"]["keys"] = None  # the page went elsewhere under the keys: the walk says nothing
        if page.url != final and not barred:
            data["page"]["keys"] = None
        # What was read must be the page asked for, or one the rules admit: a page that tried to
        # leave for a closed address, at any moment, or renamed itself to one, is not recorded.
        why = barred[0] if barred else closed(final) and f"moves to {final}, where {closed(final)}"
        if why:
            raise Refused(why)
    finally:
        ctx.close()

    host = urllib.parse.urlsplit(final).hostname or ""
    for f in fetched:
        other = urllib.parse.urlsplit(f["url"]).hostname or ""
        f["third"] = bool(other) and other != host and not other.endswith("." + host)
        f["url"] = f["url"][:300]
        if "from" in f:
            f["from"] = f["from"][:300]
    thirds = {urllib.parse.urlsplit(f["url"]).hostname for f in fetched if f["third"]}
    images = {f["url"]: (f["mime"], f["bytes"]) for f in fetched if f["mime"].startswith("image/")}
    try:
        ipv6 = bool(socket.getaddrinfo(host, None, socket.AF_INET6))
    except OSError:
        ipv6 = False
    data["page"].update(grows=grows, tls=secured, ipv6=ipv6)

    widgets = []
    for s in data["surfaces"]:
        if s["kind"] == "img" and s.get("src") in images:
            s["mime"], s["bytes"] = images[s["src"]]
            origin, manifest = origins.get(s["src"], (None, False))
            if origin:
                s["origin"] = origin
            if manifest:
                s["manifest"] = True
        s["key"] = key(s)
    for src in data.pop("sources"):
        for mark, vendor in WIDGETS.items():
            if mark in src and vendor not in {w["vendor"] for w in widgets}:
                widgets.append({"kind": "widget", "vendor": vendor, "sel": src[:120],
                                "order": len(data["surfaces"]) + len(widgets)})
    for w in widgets:
        w["key"] = key(w)

    digest = hashlib.sha256(shot).hexdigest()
    if shots:
        Path(shots).mkdir(parents=True, exist_ok=True)
        Path(shots, digest[:16] + ".png").write_bytes(shot)

    return {
        "url": final, "requested": url, "at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "agent": AGENT, "browser": f"Chromium {browser.version}", "page": data["page"],
        "network": {"requests": len(fetched), "transfer": sum(f["bytes"] for f in fetched),
                    "thirdParties": sorted(thirds), "resources": fetched},
        "surfaces": data["surfaces"] + widgets, "events": data["events"], "shot": digest,
    }


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("urls", nargs="+")
    ap.add_argument("--contact", required=True, metavar="URL",
                    help="where site owners can read what this robot does and reach its operator")
    ap.add_argument("--shots", metavar="DIR", help="keep full-page screenshots here")
    ap.add_argument("--mandate", metavar="REF",
                    help="reference of the site owner's written leave to observe despite robots.txt")
    args = ap.parse_args()
    agent = f"{AGENT}; +{args.contact}"
    rules, last, shut, status = {}, {}, {}, 0
    for stream in (sys.stdout, sys.stderr):  # the same bytes on every system: UTF-8, line feeds alone
        stream.reconfigure(encoding="utf-8", newline="\n")

    def refusal(url, mandated):
        """Why this address is closed to the robot, or None."""
        where = place(url)
        if where is None:
            return "not a web address"
        origin = where[0]
        if origin not in rules:
            rules[origin] = robots(origin, agent)
        if rules[origin] is None:
            return "robots.txt unreachable"
        return None if mandated or rules[origin].can_fetch(AGENT, url) else "robots.txt refuses"

    def leave(url, why):
        nonlocal status
        print(f"observe: {url}: {why}; left alone", file=sys.stderr)
        status = 3

    with sync_playwright() as pw:
        browser = pw.chromium.launch()
        for url in args.urls:
            origin, site = place(url) or (None, None)
            why = shut.get(site) or refusal(url, args.mandate)
            if why:
                leave(url, why)
                continue
            wait = max(PAUSE, rules[origin].crawl_delay(AGENT) or 0)
            time.sleep(max(0, wait - (time.monotonic() - last.get(site, -1e9))))
            try:  # the mandate covers the site it was given for, wherever on that site the page leads
                record = observe(browser, url, agent, args.shots,
                                 lambda to: refusal(to, args.mandate and (place(to) or (None, None))[1] == site))
            except Refused as r:
                leave(url, str(r))
                if r.whole:
                    shut[site] = f"the site said no earlier in this run ({r})"
                continue
            except BrowserError as e:
                leave(url, "could not load: " + str(e).splitlines()[0])
                continue
            finally:
                last[site] = time.monotonic()
            if args.mandate:
                record["mandate"] = args.mandate
            print(json.dumps(record), flush=True)  # ASCII alone: no shell can re-encode it
        browser.close()
    sys.exit(status)


if __name__ == "__main__":
    main()
